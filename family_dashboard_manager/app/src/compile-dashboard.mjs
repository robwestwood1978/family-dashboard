import { validateConfig } from "./validate-config.mjs";

const VIEW_ORDER = ["today", "calendar", "rooms", "family", "music", "football"];

function sortValue(value) {
  if (Array.isArray(value)) return value.map(sortValue);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, sortValue(value[key])])
  );
}

export function getEnabledViewPaths(config) {
  const enabled = VIEW_ORDER.filter((view) => view === "today" || config.features[view] === true);
  const defaultIndex = enabled.indexOf(config.display.default_view);
  if (defaultIndex <= 0) return enabled;
  return [
    enabled[defaultIndex],
    ...enabled.slice(0, defaultIndex),
    ...enabled.slice(defaultIndex + 1)
  ];
}

function yamlBlock(value, indent) {
  const prefix = " ".repeat(indent);
  return JSON.stringify(value, null, 2)
    .split("\n")
    .map((line) => `${prefix}${line}`)
    .join("\n");
}

/**
 * Compile the one-card Home Assistant panel used by the v0.5 Family Hub.
 * Navigation and presentation live inside the first-party card so the tablet
 * does not have to construct a large tree of third-party Lovelace cards.
 */
export function compileDashboard(candidate) {
  const config = sortValue(validateConfig(structuredClone(candidate)));
  const cardConfig = structuredClone(config);
  // Deferred high-risk mappings may remain in the private manager config for
  // migration, but v0.5 never sends them into the tablet frontend.
  delete cardConfig.entry;
  const lines = [
    "# Generated by Family Dashboard Manager. Do not edit by hand.",
    `title: ${JSON.stringify(config.product.title)}`
  ];

  if (config.display.kiosk) {
    lines.push(
      "kiosk_mode:",
      "  non_admin_settings:",
      "    kiosk: true",
      "  admin_settings:",
      "    kiosk: false"
    );
  }

  lines.push(
    "views:",
    "  - title: \"Family Hub\"",
    "    path: hub",
    "    icon: mdi:home-heart",
    "    type: panel",
    "    cards:",
    "      - type: custom:family-hub-card",
    "        config_json: |-",
    yamlBlock(cardConfig, 10),
    ""
  );

  return lines.join("\n");
}
